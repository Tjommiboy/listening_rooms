export const dictionaries: Record<Locale, Dictionary> = { nb, en };

export function isLocale(value: unknown): value is Locale {
  return LOCALES.includes(value as Locale);
}

/** Number formatting per language (1,5 GB in Norwegian, 1.5 GB in English). */
export function formatNumber(locale: Locale, value: number, digits: number) {
  return new Intl.NumberFormat(locale === "nb" ? "nb-NO" : "en-GB", {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  }).format(value);
}
